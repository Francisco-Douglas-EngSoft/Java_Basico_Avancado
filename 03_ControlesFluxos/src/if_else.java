public class if_else {
    public static void main(String[] args) {
        int idade = 18;

        if (idade >= 18) {
            System.out.println("Você é maior de idade.");
        } else if (idade < 18) {
            System.out.println("Você é menor de idade.");
        } else {
            System.out.println("Idade inválida.");
        }
    }
    
}
