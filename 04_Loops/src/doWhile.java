public class doWhile {
    public static void main(String[] args) {
        int i = 0;

        // "do" significa "faça": executa o bloco de codigo pelo menos uma vez.
        do {
            System.out.println("O valor de i e: " + i);
            i++;
        } while (i < 10); // "while" significa "enquanto": repete enquanto i for menor que 10.
    }
}
