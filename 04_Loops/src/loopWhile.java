public class loopWhile {
    public static void main(String[] args) {
        // A contagem comeca em 0.
        int i = 0;

        // "while" significa "enquanto": repete enquanto i for menor que 10.
        while (i < 10) {
            System.out.println("O valor de i e: " + i);

            // Soma 1 a i para a contagem avancar e o loop terminar.
            i++;
        }
    }
}
