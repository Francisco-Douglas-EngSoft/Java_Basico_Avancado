public class op_unarios {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        // Operadores unários
        int positivo = +a;
        int negativo = -b;
        boolean not = !true;

        System.out.println("Positivo: " + positivo);
        System.out.println("Negativo: " + negativo);
        System.out.println("NOT: " + not);
    }
}
