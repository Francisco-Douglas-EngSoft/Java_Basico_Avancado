public class op_atribuicao {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        // Operadores de atribuição
        a += b; // a = a + b
        System.out.println("Atribuição (a += b): " + a);

        a -= b; // a = a - b
        System.out.println("Atribuição (a -= b): " + a);

        a *= b; // a = a * b
        System.out.println("Atribuição (a *= b): " + a);

        a /= b; // a = a / b
        System.out.println("Atribuição (a /= b): " + a);

        a %= b; // a = a % b
        System.out.println("Atribuição (a %= b): " + a);
    }
}
