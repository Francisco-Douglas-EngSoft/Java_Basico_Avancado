public class PromocoesAutomaticas {
    public static void main(String[] args){
        //Promoções automáticas em Java e o ato de criar 
        // uma classe para representar uma promoção automática.

        byte a = 10;
        int b = a + 5; // Promoção automática de byte para int
        System.out.println("Valor de b: " + b);

        int a1 = 10;
        long b1 = 15L;
        long c = a1 + b1; // Promoção automática de int para long
        System.out.println("Valor de c: " + c);
    }
    
}
